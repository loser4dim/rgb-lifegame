import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
const { instance } = await WebAssembly.instantiate(readFileSync("public/wasm/rgb_life.wasm"), {});
const e = instance.exports;
assert.equal(e.init(5,5),1);
const image=new Uint8Array(e.memory.buffer,e.image_ptr(),100);
for(let i=0;i<25;i++)image[i*4+3]=255;
for(const i of [11,12,13])image[i*4]=255;
for(const i of [6,7,11,12])image[i*4+1]=255;
e.seed(127,127,127,0,0);e.step(0);
const cells=new Uint8Array(e.memory.buffer,e.cells_ptr(),25);
for(let i=0;i<25;i++)assert.equal(cells[i],([7,12,17].includes(i)?1:0)|([6,7,11,12].includes(i)?2:0));
const pixels=new Uint8Array(e.memory.buffer,e.render(7),100);
assert.deepEqual([...pixels.slice(12*4,12*4+4)],[255,255,0,255]);
const blue=new Uint8Array(e.memory.buffer,e.render(4),100);
assert.deepEqual([...blue.slice(12*4,12*4+4)],[0,0,0,255]);
assert.equal(e.init(513,5),0);
e.init(384,256);new Uint8Array(e.memory.buffer,e.image_ptr(),384*256*4).fill(255);e.seed(127,127,127,1,0);e.step(1);
assert.equal(new Uint8Array(e.memory.buffer,e.cells_ptr(),384*256).every(v=>v===0),true);
console.log("WASM integration passed: image seed, independent RGB, synchronous update, composite colors, layer mask, bounds, full-sized grid.");
